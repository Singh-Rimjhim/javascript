/*Operator precedance
JavaScript follows mathematical order(BODMAS).
*/
let result = 10 + 5 * 2;
console.log(result); //20
//String addition
let a = "10";
let b = "20";
console.log(a + b); //1020

let name = "Rimjhim";
let age = 19;
console.log(name + age);//Rimjhim19
console.log(`My name is ${name} and I am ${age} years old.`);
//My name is Rimjhim and I am 19 years old.

